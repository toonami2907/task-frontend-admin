const AdminEmojiPicker = ({ isOpen, onEmojiSelect, onClose }) => {
  const [searchTerm, setSearchTerm] = useState('');
  const pickerRef = useRef(null);

  const filteredEmojis = emojis.filter(emoji => 
    emoji.includes(searchTerm) || searchTerm === ''
  );

  useEffect(() => {
    const handleClickOutside = (event) => {
      if (pickerRef.current && !pickerRef.current.contains(event.target)) {
        onClose();
      }
    };

    if (isOpen) {
      document.addEventListener('mousedown', handleClickOutside);
    }

    return () => {
      document.removeEventListener('mousedown', handleClickOutside);
    };
  }, [isOpen, onClose]);

  const handleEmojiClick = (emoji) => {
    onEmojiSelect(emoji);
  };

  return (
    <AnimatePresence>
      {isOpen && (
        <motion.div
        ref={pickerRef}
        initial={{ opacity: 0, scale: 0.95, y: 10 }}
        animate={{ opacity: 1, scale: 1, y: 0 }}
        exit={{ opacity: 0, scale: 0.95, y: 10 }}
        transition={{ duration: 0.2 }}
        className="absolute bottom-full left-0 mb-2 bg-white dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-lg shadow-lg p-4 w-80 max-h-64 overflow-hidden z-50"
      >
        <div className="mb-3">
          <input
            type="text"
            placeholder="Search emojis..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="w-full px-3 py-2 text-sm border border-gray-200 dark:border-gray-600 rounded-md bg-gray-50 dark:bg-gray-700 text-gray-900 dark:text-gray-100 focus:outline-none focus:ring-2 focus:ring-blue-500"
          />
        </div>
        
        <div className="grid grid-cols-8 gap-1 max-h-40 overflow-y-auto">
          {filteredEmojis.map((emoji, index) => (
            <button
              key={index}
              onClick={() => handleEmojiClick(emoji)}
              className="w-8 h-8 flex items-center justify-center text-lg hover:bg-gray-100 dark:hover:bg-gray-700 rounded transition-colors"
            >
              {emoji}
            </button>
          ))}
        </div>
        
        {filteredEmojis.length === 0 && (
          <div className="text-center text-gray-500 dark:text-gray-400 py-4">
            No emojis found
          </div>
        )}
        </motion.div>
      )}
    </AnimatePresence>
  );
};

AdminEmojiPicker.propTypes = {
  isOpen: PropTypes.bool.isRequired,
  onEmojiSelect: PropTypes.func.isRequired,
  onClose: PropTypes.func.isRequired,
};

export default AdminEmojiPicker;
